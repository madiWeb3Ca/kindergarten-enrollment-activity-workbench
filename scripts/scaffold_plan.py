TEMPLATES = {"single": SINGLE, "series": SERIES, "resource": RESOURCE}


def main():
    parser = argparse.ArgumentParser(description="生成招生活动骨架（方案卡/排期表/资源建档）")
    parser.add_argument("--title", required=True, help="活动/场所名称")
    parser.add_argument("--kind", choices=KINDS, default="single",
                        help="产物类型：single 单场方案卡／series 排期表／resource 资源建档")
    parser.add_argument("--layer", choices=list(LAYERS), default=None, help="主攻年龄层（single 用）")
    parser.add_argument("--window", choices=WINDOWS, default="长期蓄水", help="招生窗口")
    parser.add_argument("--mode", choices=MODES, default="走出去", help="活动主干模式（single 用）")
    parser.add_argument("--place", choices=PLACES, default="【待填】", help="场所类型（single 用，记资源库类型字段）")
    parser.add_argument("--goal", choices=GOALS, default="留资", help="主目标（single 用）")
    parser.add_argument("--out", default=None, help="输出路径（默认 名称.html）")
    parser.add_argument("--format", choices=["html", "md"], default="html",
                        help="输出格式：html（默认）或 md（纯文本底稿）")
    args = parser.parse_args()

    if not args.title.strip():
        print("[错误] 请用 --title 提供活动/场所名称（不能为空）", file=sys.stderr)
        return 2

    layer = LAYERS.get(args.layer, "【待填：主攻年龄层】")
    content = TEMPLATES[args.kind].format(
        title=args.title.strip(),
        layer=layer,
        window=args.window,
        mode=args.mode,
        place=args.place,
        goal=args.goal,
    )

    ext = ".html" if args.format == "html" else ".md"
    base = args.out or args.title.strip()
    root, given = os.path.splitext(base)
    if given.lower() in (".md", ".html"):
        base = root
    out = base + ext

    out_dir = os.path.dirname(os.path.abspath(out))
    try:
        os.makedirs(out_dir, exist_ok=True)
        payload = render_markdown(content) if args.format == "html" else content
        with open(out, "w", encoding="utf-8") as f:
            f.write(payload)
    except OSError as e:
        print(f"[错误] 输出文件写入失败：{e}", file=sys.stderr)
        return 2

    print(f"[完成] 已生成骨架：{out}")
    if args.kind == "single":
        print(f"[提示] 主攻 {layer}，窗口 {args.window}，主目标 {args.goal}")
    elif args.kind == "series":
        print("[提示] 排期表先定节奏，确认后逐场展开成方案卡")
    else:
        print("[提示] 资源建档条目回填外联资源库表，挂场所编码关联活动档案")
    if args.format == "html":
        print("[提示] HTML 可直接双击阅读、Ctrl+P 打印或存 PDF；黄色高亮为待填/待核实处")
    print("[下一步] 按 references/ 填充内容，再跑 check_plan.py 自检")
    return 0


if __name__ == "__main__":
    sys.exit(main())
